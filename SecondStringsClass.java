class SecondStringsClass{
    public static void main(String[] args){
        String name1="praveen";
        String name2="kumar";
        String name=name1 + name2;
        System.out.println(name.length());
        for(int i=0;i<name.length();i++){
            System.out.println(name.charAt(i));
        }
    }
}
